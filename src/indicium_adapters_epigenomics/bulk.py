"""BulkEpigenomicsAdapter — bulk epigenomics assay and biology adapter.

Covers bulk-level epigenomics claims across the major assay families:

- Chromatin binding / histone modification (ChIP-seq, CUT&RUN, CUT&Tag)
- Chromatin accessibility (ATAC-seq, MNase-seq, DNase-seq)
- DNA methylation (WGBS, RRBS, EM-seq)
- Chromosome conformation (Hi-C, Micro-C, ChIA-PET, HiChIP)

Single-cell-resolution qualifiers live in ``SingleCellEpigenomicsAdapter`` and
methylation-array-specific qualifiers in ``MethylationArrayEpigenomicsAdapter``
to keep the three sibling qualifier sets disjoint.

The adapter is a pure-function claim enricher. It does not perform LLM
extraction, does not call out to external services, and does not write files.
Domain-specific data (histone mark / chromatin-target / assay / assembly / QC
lookup tables) is shipped as bundled package resources, regenerated by
maintainer scripts under ``data/build_*.py``.
"""
from __future__ import annotations

import copy
from importlib.resources import files
from typing import Final

import rdflib

from indicium_adapters_epigenomics._enrichment import (
    ASSAY_INDEX,
    ASSEMBLY_INDEX,
    HISTONE_INDEX,
    QC_INDEX,
    TARGET_INDEX,
)
from indicium_adapters_epigenomics._namespaces import EPIGENOMICS_PREFIXES
from indicium_adapters_epigenomics._registries import accession_to_curie

__all__ = ["BulkEpigenomicsAdapter", "accession_to_curie"]


# Slot names that may carry an enrichable token (accession, assay name, histone
# mark, target gene, assembly, QC metric). Kept narrow on purpose — the
# ``qualifier`` slot is included so that, e.g., a qualifier literal carrying an
# assay name can still pick up a CURIE.
_ENRICHABLE_SLOTS: Final[tuple[str, ...]] = ("subject", "object", "qualifier")


class BulkEpigenomicsAdapter:
    """Bulk epigenomics DomainAdapter (api_version=1).

    Qualifiers cover both biology-level assertions (binding, marking,
    accessibility, methylation, 3D interaction) and study-level assay-metadata
    assertions (sequencing platform, alignment / peak-calling / methylation
    quantification / normalisation / statistical-test tool, source database
    and consolidated dataset). Single-cell-only and array-only qualifiers live
    in the sibling adapters to keep the three sets pairwise disjoint.

    Enrichment recognises repository accessions (ENCODE / EpiRR / GEO / SRA /
    ENA / ArrayExpress / BioProject / EGA / ChIP-Atlas / Cistrome), assay
    names, reference-genome assembly names, histone modifications and
    variants, chromatin targets (TFs + modifiers), and QC-metric names.
    """

    domain_id = "bulk-epigenomics"
    api_version = 1

    qualifiers: frozenset[str] = frozenset({
        # Assay / study-level qualifiers — subject is typically a study or
        # capsule id, object is a platform / tool / database / accession.
        "assayed_with",
        "sequenced_on",
        "aligned_with",
        "called_peaks_with",
        "quantified_methylation_with",
        "normalized_with",
        "tested_with",
        "uses_database",
        "consolidates_dataset",
        # Biology-level qualifiers — assertions about chromatin state and
        # 3D organisation at bulk resolution.
        "bound_by",
        "marked_by",
        "accessible_in",
        "methylated_in",
        "differentially_methylated_in",
        "differentially_bound_in",
        "differentially_accessible_in",
        "enriched_for",
        "co_occupies_with",
        "interacts_3d_with",
    })

    ontology_prefixes: dict[str, str] = EPIGENOMICS_PREFIXES

    def extraction_context(self) -> str:
        return (
            "Domain: bulk epigenomics (WGBS, RRBS, EM-seq, ChIP-seq, "
            "ATAC-seq, CUT&RUN, CUT&Tag, MNase-seq, DNase-seq, Hi-C, "
            "Micro-C, ChIA-PET, HiChIP). Use one of the following "
            "qualifiers: assayed_with, sequenced_on, aligned_with, "
            "called_peaks_with, quantified_methylation_with, normalized_with, "
            "tested_with, uses_database, consolidates_dataset, bound_by, "
            "marked_by, accessible_in, methylated_in, "
            "differentially_methylated_in, differentially_bound_in, "
            "differentially_accessible_in, enriched_for, co_occupies_with, "
            "interacts_3d_with. Subjects/objects should be: histone marks "
            "like H3K27ac (for marked_by/enriched_for); chromatin-target "
            "gene symbols like CTCF (for bound_by/co_occupies_with); "
            "assay/tool names (for assayed_with/aligned_with/"
            "called_peaks_with); genome assembly names (for aligned_with); "
            "repository accessions GSExxx, SRRxxx, ENCSRxxx, IHECREXXX, "
            "EGAS/EGADxxx, PRJNAxxx, E-MTAB-xxx (for uses_database/"
            "consolidates_dataset). Cell types and tissues should be "
            "CL/UBERON labels."
        )

    def enrich_claim(self, claim: dict) -> dict:
        """Enrich a claim with epigenomics CURIEs.

        Per-slot resolution order (first non-None match wins):

        1. ``accession_to_curie`` — repository accessions (GEO/SRA/ENCODE/
           EpiRR/EGA/BioProject/ArrayExpress/ChIP-Atlas/Cistrome) resolve
           deterministically and outrank any free-text match.
        2. ``ASSAY_INDEX`` — epigenomics assay names.
        3. ``ASSEMBLY_INDEX`` — reference-genome assembly names.
        4. ``HISTONE_INDEX`` — histone PTMs / variants / DNA modifications.
        5. ``TARGET_INDEX`` — TFs and chromatin modifiers.
        6. ``QC_INDEX`` — QC-metric names.

        Pure function — never mutates the input dict.
        """
        result = copy.deepcopy(claim)
        result.setdefault("ontology_terms", {})
        result.setdefault("xrefs", {})

        for slot in _ENRICHABLE_SLOTS:
            raw = result.get(slot)
            if not isinstance(raw, str):
                continue
            value = raw.strip()
            if not value:
                continue

            match, source = _resolve(value)
            if match is None:
                continue

            result["ontology_terms"][slot] = match["curie"]
            result["xrefs"][slot] = {**match, "source": source}

        return result

    def shacl_shapes(self) -> rdflib.Graph:
        """Return ASB-claim SHACL shapes (CURIE format validation only).

        Loads ``shapes/epigenomics.shapes.ttl`` if present. The TTL is
        produced by a follow-up task; until it lands this method returns an
        empty graph so the package stays importable and Protocol-conformant.
        """
        return _load_shapes()


def _resolve(value: str) -> tuple[dict[str, str] | None, str]:
    """Try each enrichment source in precedence order. First hit wins.

    Returns ``(match_dict, source_label)`` where ``source_label`` is one of
    ``"accession" | "assay" | "assembly" | "histone" | "target" | "qc"``.
    Returns ``(None, "")`` when nothing matches.
    """
    if match := accession_to_curie(value):
        return match, "accession"
    if match := ASSAY_INDEX.lookup(value):
        return match, "assay"
    if match := ASSEMBLY_INDEX.lookup(value):
        return match, "assembly"
    if match := HISTONE_INDEX.lookup(value):
        return match, "histone"
    if match := TARGET_INDEX.lookup(value):
        return match, "target"
    if match := QC_INDEX.lookup(value):
        return match, "qc"
    return None, ""


def _load_shapes() -> rdflib.Graph:
    """Shared shapes loader. Returns an empty graph if the TTL is absent."""
    g = rdflib.Graph()
    ttl = files("indicium_adapters_epigenomics.shapes").joinpath(
        "epigenomics.shapes.ttl"
    )
    # TODO: load shapes — TTL is produced by the follow-up shapes task.
    if ttl.is_file():
        g.parse(ttl.open("rb"), format="turtle")
    return g
